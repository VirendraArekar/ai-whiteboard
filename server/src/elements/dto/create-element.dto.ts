import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  IsUUID,
} from 'class-validator';

export class CreateElementDto {
  @ApiPropertyOptional({ description: 'Client-generated UUID or generated by server' })
  @IsUUID()
  @IsOptional()
  id?: string;

  @ApiProperty({ example: 'rectangle', description: 'Element type classification' })
  @IsString()
  @IsNotEmpty()
  type: string;

  @ApiProperty({ description: 'Type-specific JSON data payload' })
  @IsNotEmpty()
  data: Record<string, any>;

  @ApiProperty({ example: 100, default: 0 })
  @IsNumber()
  positionX: number;

  @ApiProperty({ example: 100, default: 0 })
  @IsNumber()
  positionY: number;

  @ApiProperty({ example: 120, default: 100 })
  @IsNumber()
  width: number;

  @ApiProperty({ example: 80, default: 100 })
  @IsNumber()
  height: number;

  @ApiPropertyOptional({ example: 0, default: 0 })
  @IsNumber()
  @IsOptional()
  rotation?: number;

  @ApiPropertyOptional({ example: 1, default: 0 })
  @IsNumber()
  @IsOptional()
  zIndex?: number;
}
